/**
 * Writes test/positions.cases.ts: kinds of values in positions where the library converts them
 * (arguments, markup, callbacks, code). Each case the types accept is printed and compiled with Typst
 * by test/positions.test.ts; each case they reject is a `@ts-expect-error`, so that `pnpm typecheck`
 * notices a type that gets wider or narrower. Run it after a change of either: `node scripts/positions.ts`.
 */
import { writeFileSync } from 'node:fs'
import ts from 'typescript'

/** Positions: `$` is the value. */
const positions: Record<string, string> = {
  requiredContent: 'strong($)',
  optionalContent: "link('https://example.org', $)",
  contentAfterOptional: 'align($)',
  contentAfterGiven: 'align(center, $)',
  cell: "table({ columns: 2 }, 'a', $)",
  gridCell: "grid({ columns: 2 }, 'a', $)",
  namedContent: "figure({ caption: $ }, 'x')",
  namedSupplement: "figure({ supplement: $, caption: 'c' }, 'x')",
  numbers: 'calc.max(1, $)',
  namedLength: "text({ size: $ }, 'x')",
  namedInt: "heading({ level: $ }, 'x')",
  namedPaint: 'rect({ fill: $ })',
  namedSides: "block({ inset: $ }, 'x')",
  enumItem: 'enum_($)',
  termItem: 'terms($)',
  listMarker: 'set(list, { marker: $ })',
  pageNumbering: 'set(page, { numbering: $ })',
  markupLine: "inline('a', $)",
  markupBlocks: "blocks('a', $)",
  markupList: "m.list('a', $)",
  markupTerm: "m.terms(m.term('a', $))",
  labelled: "labelled($, label('k'))",
  letValue: "let_('v', $)[0]",
  dataItem: 'metadata(data([$]))',
  value: 'metadata($)',
  dictValue: 'metadata({ k: $ })',
  arrayItem: 'metadata([$])',
  codeItem: "codeBlock(['a', $])",
  codeValue: 'codeBlock([], $)',
  contextReturn: 'context(() => ($))',
  showReturn: 'show(heading, () => ($))',
  defineBody: "define('f').body(() => ($)).decl",
  defineValueBody: "define('f').returns(T.any).body(() => ($)).decl",
  numberingReturn: 'set(heading, { numbering: () => ($) })',
  cellReturn: "table({ columns: 2, fill: () => ($) }, 'a')",
  mapReturn: 'metadata(data([1]).map(() => ($)))',
  defineContentArg: 'gc($)',
  defineAnyArg: 'ga($)',
  defineNamedContent: 'gn({ note: $ })',
  defineRestArg: 'gr($)',
  contentJoin: "inline(add(strong('a'), $))",
  numberingArg: "inline(numbering('1', $))",
  boxBody: 'box($)',
  placeBody: 'place($)',
  cellBody: "table({ columns: 2 }, 'a', table.cell($))",
}

const values: Record<string, string> = {
  false: 'false',
  null: 'null',
  undefined: 'undefined',
  zero: '0',
  one: '1',
  fraction: '1.5',
  emptyString: "''",
  string: "'x'",
  emptyArray: '[]',
  stringArray: "['a']",
  mixedArray: "['a', strong('b')]",
  numberArray: '[1, 2]',
  nestedArray: "[['a'], 'b']",
  emptyObject: '{}',
  object: '{ a: 1 }',
  content: "strong('x')",
  intRef: 'n',
  strRef: 's',
  auto: 'auto',
  element: 'heading',
  arrow: '(x: Expr<any>) => x',
  thunk: '() => 1',
  length: 'pt(1)',
  color: 'red',
  data: 'data({ a: 1 })',
  true: 'true',
  ratio: 'pct(50)',
  bigint: '2n',
  statement: 'set(text, { fill: red })',
  blockArray: "['a', m.list('x')]",
}

const head = `/** Generated by scripts/positions.ts: kinds of values in positions where the library converts them. */
import {
  add, align, block, blocks, box, calc, center, codeBlock, context, data, define, enum_, figure, grid, heading, inline, label,
  labelled, let_, link, list, m, metadata, numbering, page, pct, place, pt, rect, red, set, show, strong, T, table, terms,
  text, auto, type Expr,
} from '../src/index.ts'

const [nDecl, n] = let_('n', 2)
const [sDecl, s] = let_('s', 'str')
const gc = define('gc').pos('x', T.content).body((p) => p.x)
const ga = define('ga').pos('x', T.any).returns(T.any).body((p) => p.x)
const gn = define('gn').named('note', T.content, []).body((p) => p.note)
const gr = define('gr').rest('items', T.any).returns(T.any).body((p) => p.items.pos())
/** Statements every case needs. */
export const prelude = [nDecl, sDecl, gc.decl, ga.decl, gn.decl, gr.decl]

/** [position, value, build]; the types reject the cases marked \`@ts-expect-error\`. */
export const cases: [string, string, () => unknown][] = [
`

const entries = Object.entries(positions).flatMap(([p, template]) =>
  Object.entries(values).map(([v, value]) => ({ p, v, code: template.replace('$', value) })),
)

// Which cases the types accept: one program with every case, one line each.
const probe = head + entries.map((e) => `  ['${e.p}', '${e.v}', () => ${e.code}],\n`).join('') + ']\n'
const file = new URL('../test/positions.cases.ts', import.meta.url).pathname
writeFileSync(file, probe)
const config = ts.getParsedCommandLineOfConfigFile(
  new URL('../tsconfig.json', import.meta.url).pathname,
  {},
  { ...ts.sys, onUnRecoverableConfigFileDiagnostic: () => {} },
)!
const program = ts.createProgram([file], config.options)
const source = program.getSourceFile(file)!
const first = head.split('\n').length
const rejected = new Set(
  ts.getPreEmitDiagnostics(program, source).map((d) => source.getLineAndCharacterOfPosition(d.start!).line + 1 - first),
)
const out =
  head +
  entries
    .map((e, i) => (rejected.has(i) ? '  // @ts-expect-error\n' : '') + `  ['${e.p}', '${e.v}', () => ${e.code}],\n`)
    .join('') +
  ']\n\n/** The cases the types reject, by index. */\nexport const rejected: ReadonlySet<number> = new Set(' +
  JSON.stringify([...rejected].sort((a, b) => a - b)) +
  ')\n'
writeFileSync(file, out)
console.log(`${entries.length} cases, ${rejected.size} rejected by the types`)
