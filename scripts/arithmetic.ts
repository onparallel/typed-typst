/**
 * Writes test/arithmetic.test-d.ts: for each pair of kinds that Typst adds, subtracts, multiplies or
 * divides, a type test that `add`, `minus`, `times` and `div` take them and that the result's type
 * includes what Typst gives. Pairs that Typst rejects are not tested: Typst's own error says what is
 * wrong. Needs the `typst` CLI. Run it after a change of those overloads or of Typst:
 * `node scripts/arithmetic.ts`.
 */
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

/** A kind: its TS operand (a literal, or a declared value) and its Typst value. */
const kinds: Record<string, [ts: string, typst: string]> = {
  int: ['i', 'int(1)'],
  float: ['f', 'float(1.5)'],
  intLiteral: ['2', '2'],
  floatLiteral: ['2.5', '2.5'],
  decimal: ['dec', 'decimal("1.5")'],
  length: ['len', '1pt'],
  ratio: ['rat', '50%'],
  relative: ['rel', '(1pt + 50%)'],
  fraction: ['fra', '1fr'],
  angle: ['ang', '1deg'],
  duration: ['dur', 'duration(days: 1)'],
  datetime: ['dt', 'datetime(year: 2020, month: 1, day: 1)'],
  strLiteral: ["'a'", '"a"'],
  str: ['s', '"a"'],
  content: ['c', '[a]'],
  arrayLiteral: ['[1]', '(1,)'],
  array: ['arr', '(1,)'],
  dictLiteral: ['{ a: 1 }', '(a: 1)'],
  bool: ['true', 'true'],
  color: ['col', 'red'],
  bytes: ['byt', 'bytes("a")'],
  arguments: ['args', 'arguments(1)'],
}
const ops = { add: '+', minus: '-', times: '*', div: '/' }
// Typst's names of types, as the bindings name them.
const names: Record<string, string> = { integer: 'int', string: 'str', 'relative length': 'relative', boolean: 'bool' }

const lines: string[] = []
for (const [op, symbol] of Object.entries(ops)) {
  lines.push(`  it('${op}', () => {`)
  for (const [a, [tsA, typstA]] of Object.entries(kinds)) {
    for (const [b, [tsB, typstB]] of Object.entries(kinds)) {
      let result: string | null
      try {
        const out = execFileSync('typst', ['eval', `str(type(${typstA} ${symbol} ${typstB}))`], { stdio: 'pipe' })
        const name = JSON.parse(out.toString()) as string
        result = names[name] ?? name
      } catch {
        result = null
      }
      if (result !== null) lines.push(`    covers(${op}(${tsA}, ${tsB}), '${result}') // ${a} ${symbol} ${b}`)
    }
  }
  lines.push('  })')
}

const out = `/** Generated by scripts/arithmetic.ts from what Typst gives for each pair of kinds. */
import { describe, it } from 'vitest'
import { add, div, minus, times, type Expr, type Value } from '../src/index.ts'

/** The result's type includes the kind Typst gives. */
const covers = <K extends string>(_: Expr<K>, _kind: NoInfer<K>) => {}
declare const i: Value<'int'>, f: Value<'float'>, dec: Value<'decimal'>, len: Value<'length'>, rat: Value<'ratio'>
declare const rel: Value<'relative'>, fra: Value<'fraction'>, ang: Value<'angle'>, dur: Value<'duration'>
declare const dt: Value<'datetime'>, s: Value<'str'>, c: Value<'content'>, arr: Value<'array'>, col: Value<'color'>
declare const byt: Value<'bytes'>, args: Value<'arguments'>

describe('arithmetic', () => {
${lines.join('\n')}
})
`
writeFileSync(new URL('../test/arithmetic.test-d.ts', import.meta.url), out)
